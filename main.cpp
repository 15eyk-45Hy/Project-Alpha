class TimeAccumulator {
    private:
    std::chrono::steady_clock::time_point StartTime;
    double TargetSeconds;
    
    public:
    TimeAccumulator(double seconds) : TargetSeconds(seconds) {
        Reset();
    }
    
    void Reset() {
        StartTime = std::chrono::steady_clock::now();
    }
    
    bool Check() {

        auto CurrentTime = std::chrono::steady_clock::now();
        auto ElapsedTime = std::chrono::duration_cast<std::chrono::duration<float>>(CurrentTime - StartTime);
        
        return (ElapsedTime.count() >= TargetSeconds) && (Reset(), true);
    }
    
    float CheckElapsed() {
        
        auto CurrentTime = std::chrono::steady_clock::now();
        auto ElapsedTime = std::chrono::duration_cast<std::chrono::duration<float>>(CurrentTime - StartTime);

        return ElapsedTime.count();
    };
};


inline int CounterFPS() {
    static TimeAccumulator FPScounter(1);
    static int Counter;
    static int DisplayFPS;

    bool IsPassed = FPScounter.Check();

    DisplayFPS = ((1 ^ IsPassed) * DisplayFPS) + ((IsPassed && 1) * Counter);
    Counter = (Counter + 1) * (IsPassed ^ 1);
    
    return DisplayFPS;
};


