class PhysicsEngine {
    private:
    inline static float FixedDT = 0.016f;
    inline static float AccumulatorPosX = 0.0f;
    inline static float AccumulatorPosY = 0.0f;
    public:
    inline static bool JumpPressed(Object& Obj) {
        return (((Obj._ST8b_StatusPlayer & _ST8p_ON_GROUND) >> 1) & ((GetAsyncKeyState(VK_SPACE) & 0x8000) >> 15));
    };
    
    
    inline static bool OnGround(Object& Obj) {
        return (Obj._ST8b_StatusPlayer & _ST8p_ON_GROUND) >> 1;
    };
    
    inline static void UpdateStatus_p8b(Object& Obj, bool JumpPressed) {
        bool IsOnGround = OnGround(Obj);
        bool InFly = JumpPressed | !IsOnGround;

        Obj._ST8b_StatusPlayer = (Obj._ST8b_StatusPlayer & ~_ST8p_IS_JUMPING) | (_ST8p_IS_JUMPING * InFly);
        
        int NextY = (int)Obj.Pos.Y + 1;
        int CurrentX = (int)Obj.Pos.X;
        Obj._ST8b_StatusPlayer = (Obj._ST8b_StatusPlayer & ~_ST8p_ON_GROUND) | (_ST8p_ON_GROUND * (MapGame[NextY][CurrentX] == 1));
    };
    
    
    inline static float ApplyGravity(Object& Obj) {
        return (Obj.Gravity * FixedDT);
    };
    
    inline static float ApplyFrictionObject(Object& Obj) {
        return ((Obj.Friction * Obj.Mass * Obj.Gravity) * FixedDT) * OnGround(Obj);
    };
    
    inline static Vector2D ApplyAirResistance(Object& Obj) {
        
        float ResistanceForceX = Obj.Vel.X * abs(Obj.Vel.X) * Obj.AirResistance;
        float ResistanceForceY = Obj.Vel.Y * abs(Obj.Vel.Y) * Obj.AirResistance;
        
        return { ResistanceForceX, ResistanceForceY };
    };
    
    
    inline static void ForceTransformator(Object& Obj, float GravityForce, float FrictionForce, Vector2D AirResistanceForce, bool JumpPressed) {
        //inline static const PhysicsStateAction 
        float JumpForce = -9 * (JumpPressed);
        
        bool NotOnGround = (!OnGround(Obj));
        Obj.Momentum.X = (Obj.Momentum.X > FrictionForce) * (Obj.Momentum.X - FrictionForce) + (Obj.Momentum.X < -FrictionForce) * (Obj.Momentum.X + FrictionForce); // Friction
        Obj.Momentum.Y = ((Obj.Momentum.Y + (GravityForce * Obj.Mass)) * (NotOnGround)) + (((JumpForce * Obj.Mass) * (Obj._ST8b_StatusPlayer & _ST8p_IS_JUMPING))); // Gravity
        
        Obj.Momentum.X -= AirResistanceForce.X * Obj.Mass * FixedDT; // AirResistance X
        Obj.Momentum.Y -= AirResistanceForce.Y * Obj.Mass * FixedDT; // AirResistance Y
        
        Obj.Vel.X = Obj.Momentum.X / Obj.Mass; // Velocity X
        Obj.Vel.Y = Obj.Momentum.Y / Obj.Mass; // Velocity Y
    };

    inline static void ApplyCollision(Object& Obj, float OldPosX, float OldPosY, const int (&MapGame)[MapHeight][MapWidth]) {
        AccumulatorPosX = (AccumulatorPosX + (Obj.Vel.X * FixedDT));
        AccumulatorPosY = (AccumulatorPosY + (Obj.Vel.Y * FixedDT));

        int IntAccumulatedPosX = (int)std::floor(AccumulatorPosX);
        int IntAccumulatedPosY = (int)std::floor(AccumulatorPosY);

        AccumulatorPosX -= IntAccumulatedPosX;
        AccumulatorPosY -= IntAccumulatedPosY;
        
        int IntPosX = ((int)std::floor(Obj.Pos.X)) + IntAccumulatedPosX;
        int IntPosY = ((int)std::floor(Obj.Pos.Y)) + IntAccumulatedPosY;

        int IntOldPosX = (int)std::floor(OldPosX);
        int IntOldPosY = (int)std::floor(OldPosY);

        unsigned char IsWallX = (MapGame[IntOldPosY][IntPosX] == 1);
        Obj.Momentum.X *= !IsWallX;
        Obj.Vel.X *= !IsWallX;
        AccumulatorPosX *= !IsWallX;
        Obj.Pos.X = (Obj.Pos.X * !IsWallX)+ (OldPosX * (IsWallX));

        unsigned char IsWallY = (MapGame[IntPosY][IntOldPosX] == 1);
        Obj.Momentum.Y *= !IsWallY;
        Obj.Vel.Y *= !IsWallY;
        AccumulatorPosX *= !IsWallX;
        Obj.Pos.Y = (Obj.Pos.Y * !IsWallY)+ (OldPosY * (IsWallY));
    };

    inline static void UpdatePosition(Object& Obj, float OldPosX, float OldPosY, const int (&MapGame)[MapHeight][MapWidth]) {
        
        ApplyCollision(Obj, OldPosX, OldPosY, MapGame);

        Obj.Pos.X += (Obj.Vel.X * FixedDT);
        Obj.Pos.Y += (Obj.Vel.Y * FixedDT);
    };
    
    // Main physics function
    static inline void Update(Object& Obj, float OldPosX, float OldPosY, const int (&MapGame)[MapHeight][MapWidth]) {

        UpdateStatus_p8b(Obj, JumpPressed(Obj));
        
        ForceTransformator(Obj, ApplyGravity(Obj), ApplyFrictionObject(Obj), ApplyAirResistance(Obj), JumpPressed(Obj));
        
        UpdatePosition(Obj, OldPosX, OldPosY, MapGame);
    };
    
    // Getters
    inline static float GetDT() {
        return FixedDT;
    };
};


